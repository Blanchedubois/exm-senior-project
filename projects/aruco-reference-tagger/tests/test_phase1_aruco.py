def test_design_loads_all_four():
    for name, sub in (("optimistic", "1_optimistic"), ("medium", "2_medium"),
                      ("conservative", "3_conservative"), ("spectrum", "4_spectrum")):
        d = Design.load_folder(os.path.join(V2, "designs", sub))
        assert d.grid_n == 5 and len(d.boxes) == 25 and len(d.node_ids) == 36, name
        assert abs(d.box_um - 145.4) < 1e-6 and abs(d.origin_um - 11.5) < 1e-9
        assert d.design_corner_sign == -1.0
        assert all(len(b.corner_tag_ids) == 4 for b in d.boxes), name
        if name == "spectrum":
            sizes = sorted({b.dot_um for b in d.boxes})
            assert sizes == [2.125, 2.5, 3.0, 3.5, 4.0]
            assert d.box(5).pitch_um == 5.0 and d.box(21).pitch_um == 8.875
        else:
            assert len({b.pitch_um for b in d.boxes}) == 1


def test_synthetic_marker_decodes_with_margin():
    """A clean rendered marker decodes with 0 corrected bits and a margin >= 2;
    one erased border module is never returned as clean."""
    import cv2
    from cv2 import aruco
    dic = aruco.getPredefinedDictionary(aruco.DICT_4X4_50)
    canvas = np.full((300, 300), 230, np.uint8)
    m = aruco.generateImageMarker(dic, 7, 120)
    canvas[90:210, 90:210] = m
    u8 = 255 - canvas                                             # bright-on-dark like fluorescence
    p = ArucoParams(um_per_px=1.0, edge_band_um=5.0)
    tags, info = decode_tags(u8, p, "DICT_4X4_50", tag_um=120.0)
    assert 7 in tags and tags[7].decode_class == "clean" and tags[7].margin_bits >= 2, info
    assert abs(tags[7].rot_deg) < 0.5 and abs(tags[7].side_px - 120) < 1.5
    assert tags[7].corner_sign == 1.0 and tags[7].border_errors == 0
    # damage: white-out one border module (20 px cells)
    dmg = canvas.copy(); dmg[90:110, 130:150] = 230
    tags2, _ = decode_tags(255 - dmg, p, "DICT_4X4_50", tag_um=120.0)
    assert 7 not in tags2 or tags2[7].decode_class != "clean" or tags2[7].border_errors > 0


def test_bits_detect_mirror():
    """A mirrored synthetic marker whose mirror happens to decode must vote
    'mirrored' from its bits, and a direct one 'proper'."""
    from cv2 import aruco
    dic = aruco.getPredefinedDictionary(aruco.DICT_4X4_50)
    p = ArucoParams(um_per_px=1.0, edge_band_um=5.0, error_correction_rate=1.0)
    n_direct = n_mirror = 0
    for mid in range(50):
        canvas = np.full((300, 300), 230, np.uint8)
        canvas[90:210, 90:210] = aruco.generateImageMarker(dic, mid, 120)
        t, _ = decode_tags(255 - canvas, p, tag_um=120.0)
        if mid in t and t[mid].bits_handedness == 1.0:
            n_direct += 1
        tm, _ = decode_tags(255 - canvas[:, ::-1].copy(), p, tag_um=120.0)
        for obs in tm.values():
            assert obs.bits_handedness != 1.0, (mid, obs.aruco_id, obs.n_bits_corrected, obs.mirror_dist)
            n_mirror += 1
    print(f"  info  {n_direct}/50 ids vote proper when direct; {n_mirror} mirrored decodes, none voted proper")
    assert n_direct >= 46


def test_frame_pose_without_design():
    import cv2
    from cv2 import aruco
    dic = aruco.getPredefinedDictionary(aruco.DICT_4X4_50)
    canvas = np.full((600, 600), 230, np.uint8)
    for k, (x, y) in enumerate([(60, 60), (380, 60), (60, 380), (380, 380)]):
        canvas[y:y + 100, x:x + 100] = aruco.generateImageMarker(dic, 10 + k, 100)
    M = cv2.getRotationMatrix2D((300, 300), 12.0, 1.0)
    rot = cv2.warpAffine(canvas, M, (600, 600), borderValue=230)
    tags, _ = decode_tags(255 - rot, ArucoParams(um_per_px=1.0, edge_band_um=2.0), tag_um=100.0)
    pose = frame_pose(tags)
    assert pose.n_tags == 4
    # getRotationMatrix2D(+12) turns content counter-clockwise on screen; rotations
    # are reported counter-clockwise-on-screen positive, so this reads +12
    assert abs(pose.frame_rot_deg - 12.0) < 0.5, pose.frame_rot_deg
    assert pose.rot_spread_deg < 0.3


