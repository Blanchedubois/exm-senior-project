def test_cli_runs():
    d, truth = _run("optimistic", "opt_clean")
    if d is None:
        return
    frame = truth["frames"][0]
    img = os.path.join(d, frame["files"][0] + ".ome.tif")
    out = os.path.join(d, "_cli")
    r = subprocess.run([sys.executable, os.path.join(ROOT, "scripts", "find_aruco.py"), img,
                        "--design", DESIGN_OPT, "--out", out], capture_output=True, text=True)
    assert r.returncode == 0, r.stderr
    csv_path = os.path.join(out, frame["files"][0] + "_tags.csv")
    assert os.path.exists(csv_path) and os.path.exists(os.path.join(out, frame["files"][0] + "_tags.png"))
    with open(csv_path) as f:
        rows = list(csv.DictReader(f))
    assert len(rows) == 36 and all(r["in_design"] == "True" for r in rows)
    assert "expansion" in r.stdout


