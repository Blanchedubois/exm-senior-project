def test_dummy_decode_all_ids():
    d, truth = _run("optimistic", "opt_clean")
    if d is None:
        return
    frame = truth["frames"][0]
    assert frame["label"] == 1.0
    design, u8, tags, info = _decode(d, truth, frame)
    assert not info["dupes"]
    tt = frame["tags"]
    seen = [i for i, t in tt.items() if t["in_frame"]]
    assert len(seen) == 36, len(seen)
    errs, rots = [], []
    for i in seen:
        i = int(i)
        assert i in tags and tags[i].usable, (i, tags.get(i))
        t = tags[i]; tr = tt[str(i)]
        errs.append(np.hypot(t.centre_px[0] - tr["x_raw"], t.centre_px[1] - tr["y_raw"]))
        rots.append(((t.rot_deg - tr["rot_deg"]) + 180) % 360 - 180)
        assert t.corner_sign == 1.0                          # OpenCV always returns clockwise corners
    errs, rots = np.array(errs), np.array(rots)
    print(f"  info  centre err median {np.median(errs):.3f} max {errs.max():.3f} px · "
          f"rot err median {np.median(np.abs(rots)):.3f} max {np.abs(rots).max():.3f} deg")
    assert errs.max() < 0.6, errs.max()                      # contour refinement: ~0.2 px median
    assert np.median(np.abs(rots)) < 0.6 and np.abs(rots).max() < 1.5, np.abs(rots).max()
    pose = frame_pose(tags, design)
    assert pose.handedness == -1.0 and pose.handedness_source == "bits"
    assert pose.n_hand_agree >= pose.n_tags - 1              # id 17's mirror is also a dictionary id


def test_rotation_tracks_frame():
    d, truth = _run("optimistic", "opt_warp")
    if d is None:
        return
    for frame in truth["frames"]:
        design, u8, tags, info = _decode(d, truth, frame)
        pose = frame_pose(tags, design)
        assert pose.n_tags >= 1, frame["label"]
        true_rots = [t["rot_deg"] for t in frame["tags"].values() if t["in_frame"]]
        true_rot = float(np.median(true_rots))
        err = ((pose.frame_rot_deg - true_rot) + 180) % 360 - 180
        print(f"  info  lambda {frame['label']:g}: {pose.n_tags} tags, rot {pose.frame_rot_deg:+.2f} "
              f"vs truth {true_rot:+.2f} (applied {frame['rotation_deg']:+.1f})")
        assert abs(err) < 0.3, (frame["label"], err)
        # every usable tag matches its truth within 0.8 px (measured: median ~0.2 px,
        # worst 0.64 px on the warped, lens-distorted frames)
        for i, t in tags.items():
            if t.usable and str(i) in frame["tags"]:
                tr = frame["tags"][str(i)]
                assert np.hypot(t.centre_px[0] - tr["x_raw"], t.centre_px[1] - tr["y_raw"]) < 0.8


def test_affine_recovers_expansion():
    """On a frame WITHOUT lens distortion the affine through the tag centres gives
    the expansion factor to 0.5 %. (A raw barrel-distorted frame is not an affine
    image of the design; Phase 2's correction removes that before Phase 3 fits.)"""
    d, truth = _run("optimistic", "opt_nolens")
    if d is None:
        return
    assert not truth["camera"]["lens"]
    for frame in truth["frames"]:
        design, u8, tags, info = _decode(d, truth, frame)
        A, finfo = fit_affine(design, tags)
        assert A is not None, frame["label"]
        lam = finfo["scale_px_per_um"] * truth["camera"]["um_per_px"]
        print(f"  info  lambda {frame['label']:g}: {finfo['method']} {finfo['n_matched']} tags -> {lam:.4f} "
              f"rot {finfo['rot_deg']:+.2f} sign {finfo['sign']:+.0f} [{finfo['sign_source']}] rms {finfo['centre_rms_px']:.2f} px")
        assert abs(lam / frame["label"] - 1) < 0.005, (frame["label"], lam)
        assert finfo["sign"] == -1.0
        if finfo["n_matched"] >= 3:
            assert finfo["centre_rms_px"] < 1.0


def test_affine_on_distorted_raw_is_sane():
    """On the lens-distorted raw frames the affine still fits (RANSAC keeps the
    tags), the handedness is right, and the scale is within 5 % of lambda."""
    d, truth = _run("optimistic", "opt_clean")
    if d is None:
        return
    for frame in truth["frames"]:
        design, u8, tags, info = _decode(d, truth, frame)
        A, finfo = fit_affine(design, tags)
        assert A is not None and finfo["sign"] == -1.0, frame["label"]
        lam = finfo["scale_px_per_um"] * truth["camera"]["um_per_px"]
        # barrel distortion (k1 = -0.05) magnifies the frame corners by up to ~9 %,
        # and at lambda >= 3 only the four corner tags are in frame
        assert abs(lam / frame["label"] - 1) < 0.10, (frame["label"], lam)
        if finfo["n_matched"] >= 3:
            assert finfo.get("n_inliers", 0) >= min(3, finfo["n_matched"])


def test_edge_band_flagging():
    d, truth = _run("optimistic", "opt_clean")
    if d is None:
        return
    frame = truth["frames"][0]
