def _run(design, run):
    d = os.path.join(DUMMY, design, run)
    if not os.path.exists(os.path.join(d, "truth.json")):
        print(f"  skip: dummy run {design}/{run} not generated"); return None, None
    with open(os.path.join(d, "truth.json")) as f:
        return d, json.load(f)


def _params(truth):
    cam = truth["camera"]
    return ArucoParams(um_per_px=cam["um_per_px"], psf_fwhm_um=cam["psf_fwhm_um"],
                       edge_band_um=abs(cam["lens_k1"]) * cam["fov_px"] * cam["um_per_px"] / 2.0 * 1.4)


def _decode(d, truth, frame, seed=0):
    design = Design.load(os.path.join(d, "reference_tags.json"))
    u8 = io.to_uint8_robust(io.load_tiff(os.path.join(d, frame["files"][seed] + ".ome.tif")))
    tags, info = decode_tags(u8, _params(truth), design.dict_name, tag_um=design.tag_um)
    return design, u8, tags, info


